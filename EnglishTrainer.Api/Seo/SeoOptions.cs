namespace EnglishTrainer.Api.Seo;

/// <summary>
/// Настройки видимости сайта в поиске и подключения счётчика.
/// </summary>
/// <remarks>
/// Всё, что приходит из внешних систем (идентификатор счётчика, имена файлов
/// подтверждения прав), задаётся конфигурацией, а не кодом: значения выдают
/// Яндекс и Google уже после регистрации сайта, и вшивать их в исходники
/// значило бы пересобирать приложение ради одной строки.
///
/// Пустые значения — рабочий режим: без счётчика страницы не грузят лишний
/// скрипт, без имён файлов маршруты подтверждения просто не регистрируются.
/// </remarks>
public sealed class SeoOptions
{
    public const string SectionName = "Seo";

    /// <summary>
    /// Публичный адрес сайта без завершающей косой черты: из него собираются
    /// абсолютные ссылки в <c>sitemap.xml</c>, <c>canonical</c> и разметке.
    /// </summary>
    public string PublicBaseUrl { get; set; } = "https://englishrainer.site";

    /// <summary>
    /// Номер счётчика Яндекс.Метрики. Строкой, а не числом намеренно: пустое
    /// значение из переменной окружения иначе сорвало бы привязку настроек,
    /// и приложение не стартовало бы из-за отсутствия счётчика.
    /// </summary>
    public string YandexMetrikaId { get; set; } = string.Empty;

    /// <summary>
    /// Записывать ли сессии посетителей (Вебвизор).
    /// </summary>
    /// <remarks>
    /// <para>
    /// Выключено по умолчанию. Вебвизор записывает движения мыши, нажатия и
    /// введённый текст — это персональные данные, и для него нужны согласие
    /// посетителя и пункт в политике обработки. Включать запись «на всякий
    /// случай» до появления политики — не техническое решение, а юридическое.
    /// </para>
    /// <para>
    /// Галочка в панели Метрики сама по себе записи не даёт: запись включает
    /// параметр в коде счётчика. Без этой настройки панель показывает
    /// «Вебвизор включён», а отчёт остаётся пустым.
    /// </para>
    /// </remarks>
    public bool MetrikaWebvisor { get; set; }

    /// <summary>
    /// Имя файла подтверждения прав в Яндекс.Вебмастере, например
    /// <c>yandex_1a2b3c4d5e6f7890.html</c>. Отдаётся по адресу <c>/{имя}</c>.
    /// </summary>
    public string YandexVerificationFile { get; set; } = string.Empty;

    /// <summary>
    /// Имя файла подтверждения прав в Google Search Console, например
    /// <c>google1a2b3c4d5e6f7890.html</c>.
    /// </summary>
    public string GoogleVerificationFile { get; set; } = string.Empty;

    /// <summary>Адрес без завершающей косой черты — в том виде, в каком он идёт в ссылки.</summary>
    public string BaseUrl => PublicBaseUrl.TrimEnd('/');

    /// <summary>Номер счётчика числом или <c>null</c>, если он не задан или задан неверно.</summary>
    public int? MetrikaId => int.TryParse(YandexMetrikaId, out var id) && id > 0 ? id : null;
}
