export async function render(container, context) {
    container.innerHTML = '<p class="hint">Загрузка…</p>';

    // Версия приходит из сборки. Если она не совпадает с последней записью ниже,
    // значит приложение обновили, а список правок забыли — сказать об этом честнее,
    // чем показывать несуществующие правки как выложенные.
    let running = null;

    try {
        running = await api('/api/version', { anonymous: true });
    } catch {
        // Без версии страница всё равно полезна: список правок важнее номера.
    }

    const [latest, ...previous] = releases;
    const outdated = Boolean(running?.version) && running.version !== latest.version;

    container.innerHTML = `
        <div class="card release release--lead">
            <div class="release__head">
                <span class="badge badge--brand">v${esc(latest.version)}</span>
                <span class="release__date">${esc(formatDate(latest.date))}</span>
                ${running?.version
                    ? `<span class="release__running">в приложении v${esc(running.version)}</span>`
                    : ''}
            </div>

            <h2 class="release__title">${esc(latest.title)}</h2>

            ${outdated
                ? `<p class="hint release__warning">
                       Список правок новее установленного приложения — значит обновление
                       ещё не выкачено на этот сервер.
                   </p>`
                : ''}

            ${latest.groups.map(group).join('')}
        </div>

        <div class="section-title">${icon('refresh', 'icon--sm')} Как это было раньше</div>

        ${previous.map(releaseCard).join('')}

        <div class="row" style="margin-top: 18px">
            <button type="button" class="btn btn--ghost" id="to-profile">
                ${context.public ? icon('close', 'icon--sm') : icon('user', 'icon--sm')}
                ${context.public ? 'На главную' : 'В профиль'}
            </button>
        </div>

        <p class="hint" style="margin-top: 14px">
            Список ведётся вручную, по одной записи на выпуск. Номер версии показан
            у каждой записи: по нему видно, обновилось ли приложение.
        </p>`;

    container.querySelector('#to-profile')
        .addEventListener('click', () => context.navigate(context.public ? 'home' : 'profile'));
}

/** Карточка выпуска, кроме самого свежего: он показан крупно выше. */
function releaseCard(release) {
    return `
        <div class="release">
            <div class="release__head">
                <span class="badge">v${esc(release.version)}</span>
                <span class="release__date">${esc(formatDate(release.date))}</span>
            </div>

            <div class="release__title release__title--small">${esc(release.title)}</div>

            ${release.groups.map(group).join('')}
        </div>`;
}

/** Раздел выпуска: заголовок и список правок. */
function group(section) {
    return `
        <div class="release__group">${esc(section.title)}</div>

        <ul class="release__items">
            ${section.items.map((item) => `<li>${esc(item)}</li>`).join('')}
        </ul>`;
}
